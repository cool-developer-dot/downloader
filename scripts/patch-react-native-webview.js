/**
 * Adds the hooks modules/vidorax-web needs to react-native-webview's Android sources (docs/ARCHITECTURE.md, section 4):
 * WebView creation, every network request and file downloads call the static RNCWebViewHooks class, so the module
 * needs no reflection. It also keeps app schemes (snssdk://, intent:) contained when JS does not answer
 * onShouldStartLoadWithRequest in time.
 *
 * Runs at postinstall and is idempotent. Every edit is an exact text replacement: when an anchor is missing, for example
 * after upgrading react-native-webview, it exits non-zero rather than shipping a browser without media detection.
 * Sources still carrying the v1 patch (scripts/apply-webview-media-hook.js) are migrated.
 *
 * Usage: node scripts/patch-react-native-webview.js [react-native-webview package directory]
 */
'use strict';

const fs = require('node:fs');
const path = require('node:path');

const SOURCE_DIR = path.join('android', 'src', 'main', 'java', 'com', 'reactnativecommunity', 'webview');
const CLIENT = 'RNCWebViewClient.java';
const MANAGER = 'RNCWebViewManagerImpl.kt';
const HOOKS = 'RNCWebViewHooks.java';

const HOOKS_SOURCE = `package com.reactnativecommunity.webview;

import android.webkit.WebResourceRequest;
import android.webkit.WebView;

import androidx.annotation.NonNull;
import androidx.annotation.Nullable;

import com.facebook.common.logging.FLog;

/**
 * Static hooks for the VidoraWeb module (modules/vidorax-web).
 * Generated by scripts/patch-react-native-webview.js; do not edit by hand.
 */
public final class RNCWebViewHooks {
    public interface Listener {
        /** Main thread, before the WebView loads anything. */
        void onWebViewCreated(@NonNull RNCWebView webView);

        /**
         * WebView network threads, for every request. The request waits until this returns, so it must be cheap and
         * never block; it cannot provide a response. {@code view} is null for service worker requests.
         */
        void observeRequest(@Nullable WebView view, @NonNull WebResourceRequest request);

        /** Main thread. Returning true means the listener took the download and DownloadManager is skipped. */
        boolean onDownloadStart(
            @NonNull RNCWebView webView,
            @NonNull String url,
            @Nullable String userAgent,
            @Nullable String contentDisposition,
            @Nullable String mimeType,
            long contentLength);
    }

    private static final String TAG = "RNCWebViewHooks";

    // Read without a lock: observeRequest runs for every request on several network threads.
    private static volatile Listener listener;

    private RNCWebViewHooks() {}

    public static synchronized void setListener(@NonNull Listener value) {
        listener = value;
    }

    /** Clears the listener unless another one has replaced it in the meantime. */
    public static synchronized void removeListener(@NonNull Listener value) {
        if (listener == value) {
            listener = null;
        }
    }

    public static void onWebViewCreated(@NonNull RNCWebView webView) {
        Listener current = listener;
        if (current == null) {
            return;
        }
        try {
            current.onWebViewCreated(webView);
        } catch (RuntimeException e) {
            logFailure("onWebViewCreated", e);
        }
    }

    public static void observeRequest(@Nullable WebView view, @NonNull WebResourceRequest request) {
        Listener current = listener;
        if (current == null) {
            return;
        }
        try {
            current.observeRequest(view, request);
        } catch (RuntimeException e) {
            logFailure("observeRequest", e);
        }
    }

    public static boolean onDownloadStart(
        @NonNull RNCWebView webView,
        @NonNull String url,
        @Nullable String userAgent,
        @Nullable String contentDisposition,
        @Nullable String mimeType,
        long contentLength) {
        Listener current = listener;
        if (current == null) {
            return false;
        }
        try {
            return current.onDownloadStart(webView, url, userAgent, contentDisposition, mimeType, contentLength);
        } catch (RuntimeException e) {
            logFailure("onDownloadStart", e);
            return false;
        }
    }

    /**
     * Result of shouldOverrideUrlLoading when JS did not decide in time (true cancels the navigation). Web pages
     * still load so a busy JS thread does not break browsing, but app schemes are never opened undecided.
     */
    public static boolean cancelsUndecidedNavigation(@Nullable String url) {
        return url == null
            || !(url.regionMatches(true, 0, "http:", 0, 5)
                || url.regionMatches(true, 0, "https:", 0, 6)
                || url.regionMatches(true, 0, "about:", 0, 6));
    }

    // A hook failure must never break browsing. Only the exception type is logged because messages can contain URLs.
    private static void logFailure(String hook, RuntimeException e) {
        FLog.w(TAG, hook + " hook failed: " + e.getClass().getName());
    }
}
`;

// RNCWebViewClient.java, pristine 13.16.1.

const PRISTINE_TIMEOUT = `if (SystemClock.elapsedRealtime() - startTime > SHOULD_OVERRIDE_URL_LOADING_TIMEOUT) {
                            FLog.w(TAG, "Did not receive response to shouldOverrideUrlLoading in time, defaulting to allow loading.");
                            RNCWebViewModuleImpl.shouldOverrideUrlLoadingLock.removeLock(lockIdentifier);
                            return false;
                        }`;

const PRISTINE_INTERRUPT = `} catch (InterruptedException e) {
                FLog.e(TAG, "shouldOverrideUrlLoading was interrupted while waiting for result.", e);
                RNCWebViewModuleImpl.shouldOverrideUrlLoadingLock.removeLock(lockIdentifier);
                return false;
            }`;

const SHOULD_OVERRIDE_WITH_REQUEST = `    @TargetApi(Build.VERSION_CODES.N)
    @Override
    public boolean shouldOverrideUrlLoading(WebView view, WebResourceRequest request) {
        final String url = request.getUrl().toString();
        return this.shouldOverrideUrlLoading(view, url);
    }`;

// RNCWebViewClient.java as left by the v1 script.

const V1_TIMEOUT = `if (SystemClock.elapsedRealtime() - startTime > SHOULD_OVERRIDE_URL_LOADING_TIMEOUT) {
                            FLog.w(TAG, "Did not receive response to shouldOverrideUrlLoading in time.");
                            RNCWebViewModuleImpl.shouldOverrideUrlLoadingLock.removeLock(lockIdentifier);
                            // VidoraX: never default-allow custom schemes (TikTok snssdk).
                            // HTTP(S) still default-allow so a slow JS bridge does not freeze pages.
                            if (url != null) {
                                String lower = url.toLowerCase();
                                if (lower.startsWith("http:") || lower.startsWith("https:") || lower.startsWith("about:")) {
                                    return false;
                                }
                            }
                            return true;
                        }`;

const V1_INTERRUPT = `} catch (InterruptedException e) {
                FLog.e(TAG, "shouldOverrideUrlLoading was interrupted while waiting for result.", e);
                RNCWebViewModuleImpl.shouldOverrideUrlLoadingLock.removeLock(lockIdentifier);
                if (url != null) {
                    String lower = url.toLowerCase();
                    if (lower.startsWith("http:") || lower.startsWith("https:") || lower.startsWith("about:")) {
                        return false;
                    }
                }
                return true;
            }`;

const V1_INTERCEPT = `

    /**
     * VidoraX: passive media observation. Never replaces the response.
     * Observation is filtered + rate-limited inside MediaNetworkBridge.
     */
    @Override
    public WebResourceResponse shouldInterceptRequest(WebView view, WebResourceRequest request) {
        try {
            // Reflection avoids a compile-time dependency on the host app package.
            Class<?> bridge = Class.forName("com.anonymous.vidorax.mediadetection.MediaNetworkBridge");
            bridge.getMethod("observeRequest", WebView.class, WebResourceRequest.class)
                    .invoke(null, view, request);
        } catch (Throwable ignored) {
            // Detection must never break browsing.
        }
        return super.shouldInterceptRequest(view, request);
    }
`;

// Replacements that turn v1-patched text back into pristine text before the edits below run.
const V1_REVERSALS = {
  [CLIENT]: [
    { from: V1_TIMEOUT, to: PRISTINE_TIMEOUT },
    { from: V1_INTERRUPT, to: PRISTINE_INTERRUPT },
    { from: SHOULD_OVERRIDE_WITH_REQUEST + V1_INTERCEPT, to: SHOULD_OVERRIDE_WITH_REQUEST },
  ],
};

const EDITS = {
  [CLIENT]: [
    {
      name: 'contain undecided navigations after the timeout',
      from: PRISTINE_TIMEOUT,
      to: `if (SystemClock.elapsedRealtime() - startTime > SHOULD_OVERRIDE_URL_LOADING_TIMEOUT) {
                            FLog.w(TAG, "Did not receive response to shouldOverrideUrlLoading in time.");
                            RNCWebViewModuleImpl.shouldOverrideUrlLoadingLock.removeLock(lockIdentifier);
                            return RNCWebViewHooks.cancelsUndecidedNavigation(url);
                        }`,
    },
    {
      name: 'contain undecided navigations after an interrupt',
      from: PRISTINE_INTERRUPT,
      to: `} catch (InterruptedException e) {
                FLog.e(TAG, "shouldOverrideUrlLoading was interrupted while waiting for result.", e);
                RNCWebViewModuleImpl.shouldOverrideUrlLoadingLock.removeLock(lockIdentifier);
                return RNCWebViewHooks.cancelsUndecidedNavigation(url);
            }`,
    },
    {
      name: 'observe requests in shouldInterceptRequest',
      from: SHOULD_OVERRIDE_WITH_REQUEST,
      to: `${SHOULD_OVERRIDE_WITH_REQUEST}

    @Override
    public WebResourceResponse shouldInterceptRequest(WebView view, WebResourceRequest request) {
        RNCWebViewHooks.observeRequest(view, request);
        return super.shouldInterceptRequest(view, request);
    }`,
    },
  ],
  [MANAGER]: [
    {
      name: 'hand downloads to the hook before DownloadManager',
      from: `        webView.setDownloadListener(DownloadListener { url, userAgent, contentDisposition, mimetype, contentLength ->
            val module =`,
      to: `        webView.setDownloadListener(DownloadListener { url, userAgent, contentDisposition, mimetype, contentLength ->
            if (RNCWebViewHooks.onDownloadStart(webView, url, userAgent, contentDisposition, mimetype, contentLength)) {
                return@DownloadListener
            }
            val module =`,
    },
    {
      name: 'report WebView creation before any load',
      from: `        return RNCWebViewWrapper(context, webView)
    }`,
      to: `        RNCWebViewHooks.onWebViewCreated(webView)
        return RNCWebViewWrapper(context, webView)
    }`,
    },
  ],
};

function countOccurrences(text, part) {
  return text.split(part).length - 1;
}

function patchSource(fileName, original, version) {
  let text = original;
  for (const { from, to } of V1_REVERSALS[fileName] ?? []) {
    if (text.includes(from)) {
      text = text.replace(from, () => to);
    }
  }
  for (const { name, from, to } of EDITS[fileName]) {
    if (text.includes(to)) {
      continue;
    }
    const count = countOccurrences(text, from);
    if (count !== 1) {
      const problem = count === 0 ? 'anchor not found' : `anchor found ${count} times`;
      throw new Error(
        `${fileName}: ${problem} for "${name}" (react-native-webview ${version}). ` +
          'Update scripts/patch-react-native-webview.js for this version.',
      );
    }
    text = text.replace(from, () => to);
  }
  return text;
}

function readPackageVersion(packageDir) {
  const manifest = path.join(packageDir, 'package.json');
  if (!fs.existsSync(manifest)) {
    throw new Error(`react-native-webview is not installed at ${packageDir}.`);
  }
  return JSON.parse(fs.readFileSync(manifest, 'utf8')).version ?? 'unknown';
}

/**
 * Patches the package in place. Nothing is written unless every edit applies.
 * @returns {string[]} names of the files that changed (empty when already patched)
 */
function patchReactNativeWebView(packageDir) {
  const version = readPackageVersion(packageDir);
  const sourceDir = path.join(packageDir, SOURCE_DIR);

  const results = [CLIENT, MANAGER].map((name) => {
    const file = path.join(sourceDir, name);
    if (!fs.existsSync(file)) {
      throw new Error(`${name} not found in ${sourceDir} (react-native-webview ${version}).`);
    }
    const original = fs.readFileSync(file, 'utf8');
    return { file, original, patched: patchSource(name, original, version) };
  });
  const hooksFile = path.join(sourceDir, HOOKS);
  results.push({
    file: hooksFile,
    original: fs.existsSync(hooksFile) ? fs.readFileSync(hooksFile, 'utf8') : null,
    patched: HOOKS_SOURCE,
  });

  const changed = results.filter(({ original, patched }) => original !== patched);
  for (const { file, patched } of changed) {
    fs.writeFileSync(file, patched);
  }
  return changed.map(({ file }) => path.basename(file));
}

function installedPackageDir() {
  try {
    return path.dirname(require.resolve('react-native-webview/package.json'));
  } catch {
    throw new Error('react-native-webview is not installed.');
  }
}

if (require.main === module) {
  try {
    const packageDir = process.argv[2] ? path.resolve(process.argv[2]) : installedPackageDir();
    const changed = patchReactNativeWebView(packageDir);
    console.log(
      changed.length > 0
        ? `[patch-react-native-webview] Patched ${changed.join(', ')}`
        : '[patch-react-native-webview] Already patched',
    );
  } catch (error) {
    console.error(`[patch-react-native-webview] ${error.message}`);
    process.exit(1);
  }
}

module.exports = { patchReactNativeWebView };
