#!/usr/bin/env node
// Builds src/detection/page/detector.generated.ts from the plain JavaScript in src/detection/page/src.
//
//   node scripts/build-detector.mjs           write the generated module
//   node scripts/build-detector.mjs --check   exit 1 when the generated module is out of date
//   node scripts/build-detector.mjs --stdout  print the detector script (used by the test harness)
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const sourceDir = join(root, 'src/detection/page/src');
const outputFile = join(root, 'src/detection/page/detector.generated.ts');

// Evaluation order: every file reads what earlier files put on `vdx`. JSON extractors are tried in the order
// they register, so the site-specific files come before site-generic.js.
const SOURCES = [
  'util.js',
  'transport.js',
  'candidates.js',
  'extract.js',
  'site-instagram.js',
  'site-facebook.js',
  'site-tiktok.js',
  'site-twitter.js',
  'site-reddit.js',
  'site-vimeo.js',
  'site-twitch.js',
  'site-pinterest.js',
  'site-snapchat.js',
  'site-jwplayer.js',
  'site-generic.js',
  'manifest.js',
  'bodies.js',
  'network-taps.js',
  'embedded.js',
  'players.js',
  'drm.js',
  'navigation.js',
  'main.js',
];

function buildScript() {
  const present = readdirSync(sourceDir).filter((name) => name.endsWith('.js')).sort();
  const unlisted = present.filter((name) => !SOURCES.includes(name));
  const missing = SOURCES.filter((name) => !present.includes(name));
  if (unlisted.length || missing.length) {
    throw new Error(`Detector sources out of sync. Unlisted: ${unlisted.join(', ') || '-'}; missing: ${missing.join(', ') || '-'}`);
  }

  const modules = SOURCES.map((name) => {
    const code = readFileSync(join(sourceDir, name), 'utf8').trim();
    // The script is injected as a string; ASCII-only sources rule out encoding surprises along the way.
    if (/[^\x00-\x7F]/.test(code)) throw new Error(`${name}: use \\u escapes instead of non-ASCII characters`);
    return `// ${name}\n(function () {\n${code}\n})();`;
  });

  return [
    '// VidoraX media detector. Built from src/detection/page/src by scripts/build-detector.mjs.',
    '(function () {',
    "'use strict';",
    'try {',
    'if (window.__vdx) return;',
    "Object.defineProperty(window, '__vdx', { value: true });",
    'const vdx = {};',
    ...modules,
    '} catch (_error) {',
    '// The detector must never break the page it observes.',
    '}',
    '})();',
    '',
  ].join('\n');
}

function renderModule(script) {
  return [
    '// Generated by scripts/build-detector.mjs from src/detection/page/src/*. Do not edit: run `npm run build:detector`.',
    '',
    `export const DETECTOR_SCRIPT: string = ${JSON.stringify(script)};`,
    '',
  ].join('\n');
}

function readCurrent() {
  try {
    return readFileSync(outputFile, 'utf8');
  } catch {
    return '';
  }
}

const mode = process.argv[2];
const script = buildScript();

if (mode === '--stdout') {
  process.stdout.write(script);
} else if (mode === '--check') {
  if (readCurrent() !== renderModule(script)) {
    console.error('src/detection/page/detector.generated.ts is out of date. Run `npm run build:detector`.');
    process.exit(1);
  }
} else if (mode === undefined) {
  writeFileSync(outputFile, renderModule(script));
} else {
  console.error(`Unknown option ${mode}. Use --check or --stdout.`);
  process.exit(2);
}
