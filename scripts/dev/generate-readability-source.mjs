// B15: writes src/browser/reader/vendor/readability-source.ts — Mozilla Readability's own source (node_modules) as
// string constants, so the reader can run it inside the page (the app's JS engine has no DOM). Run after updating
// @mozilla/readability: `node scripts/dev/generate-readability-source.mjs`. A unit test checks the file is current.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const lib = path.join(root, 'node_modules/@mozilla/readability');
const pkg = JSON.parse(fs.readFileSync(path.join(lib, 'package.json'), 'utf8'));

export function literal(source) {
  // JSON string, plus the two line separators JSON leaves raw (they end a JS string literal in older engines).
  return JSON.stringify(source).replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');
}

export function generate() {
  const readability = fs.readFileSync(path.join(lib, 'Readability.js'), 'utf8');
  const readerable = fs.readFileSync(path.join(lib, 'Readability-readerable.js'), 'utf8');
  return [
    '// GENERATED by scripts/dev/generate-readability-source.mjs — do not edit.',
    `// @mozilla/readability ${pkg.version} (${pkg.license}), https://github.com/mozilla/readability.`,
    '// Run inside web pages only (reader-scripts.ts); never evaluated by the app.',
    '',
    `export const READABILITY_VERSION = ${JSON.stringify(pkg.version)};`,
    '',
    `export const READABILITY_SOURCE = ${literal(readability)};`,
    '',
    `export const READERABLE_SOURCE = ${literal(readerable)};`,
    '',
  ].join('\n');
}

const target = path.join(root, 'src/browser/reader/vendor/readability-source.ts');
if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, generate());
  console.log(`wrote ${path.relative(root, target)} (${fs.statSync(target).size} bytes)`);
}
